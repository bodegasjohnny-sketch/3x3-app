"""Build js/confusables.js from Unicode's confusables.txt (UTS #39), pinned to version 18.0.0.
Usage: python3 tools/build_confusables.py [path/to/confusables.txt]
Default source: https://www.unicode.org/Public/18.0.0/security/confusables.txt (the versioned path; the older layout
/Public/security/18.0.0/ returns 404). Whatever is read, from the URL or a local file, must have SHA256 = SOURCE_SHA256
(the v18.0.0 file dated 2026-08-06, recorded 17 Oct 2026), or the script stops without writing anything.

Keeps every single-code-point, non-ASCII source whose prototype is plain ASCII letters/digits (lower-cased), e.g.
Greek ο, Armenian օ, Latin ɑ, small capital ᴏ, Cherokee Ꭺ, mathematical letters -> a/o/... Cherokee small letters take the
mapping of their capital (ꭺ -> Ꭺ -> a; ꭰ -> Ꭰ -> d). Latin small capitals missing from the file (ᴇ, ʀ, ...) are added from their names.
ASCII-to-ASCII entries (0 -> O, 1 -> l, rn -> m) are skipped: digits are folded separately by M.leet."""
import sys, re, json, hashlib, unicodedata, urllib.request
from pathlib import Path
SOURCE_URL = 'https://www.unicode.org/Public/18.0.0/security/confusables.txt'
SOURCE_SHA256 = '6ed3ee967c9dfdf6677d563c9985182fbc50a2efb7d6059cd57b2e2ce18f5b92'
src = sys.argv[1] if len(sys.argv) > 1 else None
raw_bytes = Path(src).read_bytes() if src else urllib.request.urlopen(SOURCE_URL).read()
got = hashlib.sha256(raw_bytes).hexdigest()
if got != SOURCE_SHA256: sys.exit(f'confusables.txt sha256 {got} != pinned {SOURCE_SHA256}; not writing js/confusables.js')
txt = raw_bytes.decode('utf-8')
ver = (re.search(r'^# Version: (\S+)', txt, re.M) or [None, '?'])[1]
date = (re.search(r'^# Date: (.+)$', txt, re.M) or [None, '?'])[1].strip()
raw = {}
for line in txt.splitlines():
    line = line.split('#', 1)[0].strip()
    if not line: continue
    f = [x.strip() for x in line.split(';')]
    if len(f) < 2: continue
    s = f[0].split(); t = ''.join(chr(int(h, 16)) for h in f[1].split())
    if len(s) != 1: continue
    raw[chr(int(s[0], 16))] = t
out = {}
for ch, t in raw.items():
    if ord(ch) < 128: continue
    tl = t.lower()
    if re.fullmatch(r'[a-z0-9]+', tl): out[ch] = tl
# Cherokee small letters: use their capital's prototype
for cp in list(range(0xAB70, 0xABC0)) + list(range(0x13F8, 0x13FE)):
    ch = chr(cp); up = ch.upper()
    if up != ch and up in out: out[ch] = out[up]
# Latin small capitals by name (LATIN LETTER SMALL CAPITAL X), when the file has no ASCII prototype for them
for cp in range(0x0250, 0xAB70):
    ch = chr(cp)
    try: n = unicodedata.name(ch)
    except ValueError: continue
    m = re.fullmatch(r'LATIN LETTER SMALL CAPITAL ([A-Z])', n)
    if m and ch not in out: out[ch] = m[1].lower()
# Latin letters with a stroke, bar or other modifier that the file has no ASCII prototype for (ø ɵ ł đ ɨ ħ ...)
for cp in range(0x00C0, 0x2C80):
    ch = chr(cp)
    if ch in out: continue
    try: n = unicodedata.name(ch)
    except ValueError: continue
    m = re.fullmatch(r'LATIN (?:SMALL|CAPITAL) LETTER (?:BARRED |DOTLESS |OPEN |CLOSED )?([A-Z])(?: WITH .+)?', n)
    if m: out[ch] = m[1].lower()
# Cherokee letters that look like a barred O (Ꮻ and its small form), and regional indicator symbols (🇦..🇿 -> a..z)
for ch in ['\u13eb', '\uabbb']: out.setdefault(ch, 'o')
for i in range(26): out[chr(0x1F1E6 + i)] = chr(97 + i)
body = json.dumps(dict(sorted(out.items(), key=lambda kv: ord(kv[0]))), ensure_ascii=True, separators=(',', ':'))
js = ('/* 3x3 · generated by tools/build_confusables.py from Unicode confusables.txt (UTS #39 version %s, %s). Do not edit by hand.\n'
      '   Source %s, sha256 %s.\n   Non-ASCII character -> ASCII lower-case skeleton (%d entries). Used by M3.fold (topic filter, banned words, placeholder gate). */\n'
      'window.CONFUSABLES_ASCII = %s;\n') % (ver, date, SOURCE_URL, SOURCE_SHA256, len(out), body)
Path(__file__).resolve().parent.parent.joinpath('js', 'confusables.js').write_text(js, encoding='utf-8')
print(len(out), 'entries, version', ver)
