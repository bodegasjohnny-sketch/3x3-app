"""Build js/confusables.js from Unicode's confusables.txt (UTS #39).
Usage: python3 tools/build_confusables.py [path/to/confusables.txt]
(default: downloads https://www.unicode.org/Public/security/latest/confusables.txt)

Keeps every single-code-point, non-ASCII source whose prototype is plain ASCII letters/digits (lower-cased), e.g.
Greek ο, Armenian օ, Latin ɑ, small capital ᴏ, Cherokee Ꭺ, mathematical letters -> a/o/... Cherokee small letters take the
mapping of their capital (ꭰ -> Ꭺ -> a). Latin small capitals missing from the file (ᴇ, ʀ, ...) are added from their names.
ASCII-to-ASCII entries (0 -> O, 1 -> l, rn -> m) are skipped: digits are folded separately by M.leet."""
import sys, re, json, unicodedata, urllib.request
from pathlib import Path
src = sys.argv[1] if len(sys.argv) > 1 else None
txt = Path(src).read_text(encoding='utf-8') if src else urllib.request.urlopen('https://www.unicode.org/Public/security/latest/confusables.txt').read().decode('utf-8')
ver = (re.search(r'^# Version: (\S+)', txt, re.M) or [None, '?'])[1]
date = (re.search(r'^# Date: (.+)$', txt, re.M) or [None, '?'])[1].strip()
raw = {}
for line in txt.splitlines():
    line = line.split('#', 1)[0].strip()
    if not line: continue
    f = [x.strip() for x in line.split(';')]
    if len(f) < 2: continue
    s = f[0].split(); t = ''.join(chr(int(h, 16)) for h in f[1].split())
    if len(s) != 1: continue
    raw[chr(int(s[0], 16))] = t
out = {}
for ch, t in raw.items():
    if ord(ch) < 128: continue
    tl = t.lower()
    if re.fullmatch(r'[a-z0-9]+', tl): out[ch] = tl
# Cherokee small letters: use their capital's prototype
for cp in list(range(0xAB70, 0xABC0)) + list(range(0x13F8, 0x13FE)):
    ch = chr(cp); up = ch.upper()
    if up != ch and up in out: out[ch] = out[up]
# Latin small capitals by name (LATIN LETTER SMALL CAPITAL X), when the file has no ASCII prototype for them
for cp in range(0x0250, 0xAB70):
    ch = chr(cp)
    try: n = unicodedata.name(ch)
    except ValueError: continue
    m = re.fullmatch(r'LATIN LETTER SMALL CAPITAL ([A-Z])', n)
    if m and ch not in out: out[ch] = m[1].lower()
body = json.dumps(dict(sorted(out.items(), key=lambda kv: ord(kv[0]))), ensure_ascii=True, separators=(',', ':'))
js = ('/* 3x3 · generated by tools/build_confusables.py from Unicode confusables.txt (UTS #39 version %s, %s). Do not edit by hand.\n'
      '   Non-ASCII character -> ASCII lower-case skeleton (%d entries). Used by M3.fold (topic filter, banned words, placeholder gate). */\n'
      'window.CONFUSABLES_ASCII = %s;\n') % (ver, date, len(out), body)
Path(__file__).resolve().parent.parent.joinpath('js', 'confusables.js').write_text(js, encoding='utf-8')
print(len(out), 'entries, version', ver)
